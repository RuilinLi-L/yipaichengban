def main():
    source = Path("output/doc/win_内容表述优化版.docx")
    doc = Document(str(source))
    changed = 0
    for paragraph in doc.paragraphs:
        text = paragraph.text
        if text in REPLACEMENTS:
            paragraph.text = REPLACEMENTS[text]
            changed += 1
    doc.save(str(source))
    print(f"saved: {source}")
    print(f"polished paragraphs: {changed}")


if __name__ == "__main__":
    main()
